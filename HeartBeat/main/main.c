uint8_t Buf[1024];
static void sensor_task(void *arg)
{
    uint32_t red = 0, ir = 0;
    char msg[BLE_PAYLOAD_MAX];

    while (1) {
        while (Heart_read_sample(&red, &ir)) { }   // drain FIFO, keep latest
        float temp = Temp_read();

        uint32_t SmoothRed  = MovingAverage(red);
        float    SmoothTemp = EMAFilter(temp);

        printf("Temp: %.2f C | RED: %lu | IR: %lu | RedS: %lu | TempS: %.2f\n",
               temp, (unsigned long)red, (unsigned long)ir,
               (unsigned long)SmoothRed, SmoothTemp);

        /* Pack filtered values as text: "TEMP,RED" */
        int len = snprintf(msg, sizeof(msg), "%.2f,%lu",
                           SmoothTemp, (unsigned long)SmoothRed);

        if (len > 0 && len < (int)sizeof(msg)) {
            int rc = ble_send_value(msg, (uint16_t)len);
            if (rc == -1 || rc == -3 || rc == -4) {
                printf("BLE send failed: %d\n", rc);
            }
            /* rc == -2: no laptop subscribed yet, which is normal */
        }

        vTaskDelay(pdMS_TO_TICKS(500));
    }
}

void app_main(void)
{
    /* INITIALIZE NVS */
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }
    ESP_ERROR_CHECK(ret);

    i2c_init();
    Heart_init();
    Oled_init();
    ble_start();
    OLED_Clear();
    
    vTaskDelay(pdMS_TO_TICKS(3000));
    horizontal_to_pages(OledBase,Buf);
    OLED_WriteBuffer(Oled_dev,Buf);
    xTaskCreate(sensor_task, "sensor_task", 4096, NULL, 5, NULL);
}
